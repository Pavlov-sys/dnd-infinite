#!/usr/bin/env python3
"""
Convert the SRD 5.2 JSON from the 5e-bits/5e-database project (MIT, src/2024/en) into Infinity Codex data modules.

Usage:
  git clone --depth 1 https://github.com/5e-bits/5e-database /tmp/5e-database
  python3 tools/import-srd.py /tmp/5e-database/src/2024/en

Writes js/data/srd/generated/*.js. All content is SRD 5.2 (CC-BY-4.0); see ATTRIBUTION.md.
"""
import json, os, re, sys

SRC = sys.argv[1] if len(sys.argv) > 1 else '/tmp/5e-database/src/2024/en'
OUT = os.path.join(os.path.dirname(__file__), '..', 'js', 'data', 'srd', 'generated')
os.makedirs(OUT, exist_ok=True)

def load(name):
    with open(os.path.join(SRC, f'5e-SRD-{name}.json'), encoding='utf-8') as f:
        return json.load(f)

def clean(text):
    if not text:
        return ''
    text = text.replace('â€™', "'").replace('’', "'").replace('—', '—')
    text = re.sub(r'(\w)- (\w)', r'\1\2', text)          # undo PDF hyphenation ("ex- pended")
    text = re.sub(r'[ \t]+\n', '\n', text)
    text = re.sub(r'\n[ \t]+', '\n', text)
    text = re.sub(r'(?<=[a-z,;\-])\n(?=[a-z(])', ' ', text)   # re-join lines the PDF wrapped mid-sentence
    return text.strip()

def write(name, export, data):
    path = os.path.join(OUT, f'{name}.js')
    with open(path, 'w', encoding='utf-8') as f:
        f.write(f'// GENERATED by tools/import-srd.py from SRD 5.2 (CC-BY-4.0). Do not edit by hand.\n')
        f.write(f'export const {export} = ')
        json.dump(data, f, ensure_ascii=False, separators=(',', ':'))
        f.write(';\n')
    print(f'{name}.js: {len(data)} entries, {os.path.getsize(path) // 1024} KB')

def gp(cost):
    if not cost:
        return 0
    q, u = cost.get('quantity', 0), cost.get('unit', 'gp')
    return round(q * {'cp': 0.01, 'sp': 0.1, 'ep': 0.5, 'gp': 1, 'pp': 10}[u], 4)

# ---------------------------------------------------------------- spells
spells = []
for s in load('Spells'):
    comps = ', '.join(s.get('components', []))
    if s.get('material'):
        comps += f" ({s['material']})"
    dmg = s.get('damage') or {}
    dice = None
    if dmg.get('damage_at_slot_level'):
        dice = dmg['damage_at_slot_level'].get(str(s['level'])) or list(dmg['damage_at_slot_level'].values())[0]
    elif dmg.get('damage_at_character_level'):
        dice = dmg['damage_at_character_level'].get('1')
    dtype = (dmg.get('damage_type') or {}).get('index')
    heal = s.get('heal_at_slot_level')
    entry = {
        'id': s['index'], 'name': s['name'], 'level': s['level'], 'school': s['school']['name'],
        'time': s.get('casting_time', ''), 'range': s.get('range', ''), 'components': comps, 'duration': s.get('duration', ''),
        'classes': [c['index'] for c in s.get('classes', [])], 'desc': clean(s.get('description') or '\n'.join(s.get('desc', []))),
        'concentration': bool(s.get('concentration')), 'ritual': bool(s.get('ritual')),
    }
    if s.get('higher_level'):
        hl = s['higher_level']
        entry['higherLevel'] = clean(hl if isinstance(hl, str) else '\n'.join(hl))
    if dice:
        entry['damage'] = f"{dice.replace(' ', '')} {dtype}" if dtype else dice.replace(' ', '')
    if heal:
        entry['heal'] = heal.get(str(s['level'])) or list(heal.values())[0]
    if s.get('dc'):
        entry['save'] = s['dc']['dc_type']['index']
    if s.get('attack_type'):
        entry['attack'] = True
    if s.get('area_of_effect'):
        a = s['area_of_effect']
        entry['area'] = f"{a.get('size')}-ft {a.get('type', '').title()}"
    spells.append(entry)
write('spells', 'SPELLS', sorted(spells, key=lambda x: (x['level'], x['name'])))

# ---------------------------------------------------------------- equipment
items = []
for e in load('Equipment'):
    cats = {c['index'] for c in e.get('equipment_categories', [])}
    base = {'id': e['index'], 'name': e['name'], 'cost': gp(e.get('cost')), 'weight': e.get('weight', 0)}
    desc = clean(e.get('description') or '\n'.join(e.get('desc', []) if isinstance(e.get('desc'), list) else [e.get('desc') or '']))
    if 'weapons' in cats:
        props = [p['name'] for p in e.get('properties', [])]
        rng = e.get('throw_range') or (e.get('range') if 'ranged-weapons' in cats else None)
        w = {**base, 'type': 'weapon', 'category': 'martial' if 'martial-weapons' in cats else 'simple',
             'kind': 'ranged' if 'ranged-weapons' in cats else 'melee',
             'damage': (e.get('damage') or {}).get('damage_dice', '1'), 'dtype': ((e.get('damage') or {}).get('damage_type') or {}).get('index', 'bludgeoning'),
             'props': props, 'mastery': (e.get('mastery') or {}).get('name')}
        if rng and rng.get('long'):
            w['range'] = f"{rng['normal']}/{rng['long']}"
        if e.get('two_handed_damage'):
            w['versatile'] = e['two_handed_damage']['damage_dice']
        if desc:
            w['desc'] = desc
        items.append(w)
    elif 'armor' in cats or 'shields' in cats:
        ac = e.get('armor_class', {})
        kind = 'shield' if 'shields' in cats else 'light' if 'light-armor' in cats else 'medium' if 'medium-armor' in cats else 'heavy'
        a = {**base, 'type': 'armor', 'armorType': kind, 'ac': ac.get('base', 10)}
        if e.get('str_minimum'):
            a['strReq'] = e['str_minimum']
        if e.get('stealth_disadvantage'):
            a['stealthDis'] = True
        items.append(a)
    else:
        g = {**base, 'type': 'gear', 'desc': desc}
        sub = next((c for c in ['ammunition', 'arcane-foci', 'druidic-foci', 'holy-symbols', 'artisans-tools', 'gaming-sets', 'musical-instruments', 'other-tools', 'equipment-packs'] if c in cats), None)
        if sub:
            g['subtype'] = sub
        if e.get('contents'):
            g['contents'] = [[c['item']['index'], c.get('quantity', 1)] for c in e['contents']]
            if not desc:
                g['desc'] = 'Contains: ' + ', '.join(f"{c.get('quantity', 1)} × {c['item']['name']}" if c.get('quantity', 1) > 1 else c['item']['name'] for c in e['contents']) + '.'
        if e.get('quantity', 1) > 1 and sub == 'ammunition':
            # Bundles (e.g. 20 arrows for 1 GP) are tracked per piece in the inventory.
            g['bundle'] = e['quantity']
            g['cost'] = round(g['cost'] / e['quantity'], 4)
            g['weight'] = round((g['weight'] or 0) / e['quantity'], 4)
        items.append(g)
write('equipment', 'ITEMS', items)

# ---------------------------------------------------------------- magic items
magic = []
for m in load('Magic-Items'):
    desc = m.get('desc') or m.get('description') or ''
    if isinstance(desc, list):
        desc = '\n'.join(desc)
    lines = clean(desc).split('\n', 1)
    magic.append({'id': f"magic-{m['index']}", 'name': m['name'], 'type': 'magic-item', 'category': m['equipment_category']['name'],
                  'rarity': m['rarity']['name'], 'attunement': bool(m.get('attunement')),
                  'subtitle': lines[0].strip() if len(lines) > 1 else '', 'desc': (lines[1] if len(lines) > 1 else lines[0]).strip(),
                  'cost': 0, 'weight': 0, **({'variant': True} if m.get('variant') else {})})
write('magic-items', 'MAGIC_ITEMS', magic)

# ---------------------------------------------------------------- monsters
def actions(lst):
    return [{'name': a['name'], 'desc': clean(a.get('desc', '')), **({'usage': a['usage']} if a.get('usage') else {})} for a in (lst or [])]

monsters = []
for m in load('Monsters'):
    ac = m.get('armor_class') or [{}]
    profs = m.get('proficiencies') or []
    saves = {p['proficiency']['index'].split('-')[-1]: p['value'] for p in profs if p['proficiency']['index'].startswith('saving-throw')}
    skills = {p['proficiency']['name'].replace('Skill: ', ''): p['value'] for p in profs if p['proficiency']['index'].startswith('skill')}
    monsters.append({
        'id': m['index'], 'name': m['name'], 'size': m.get('size'), 'kind': m.get('type'), 'alignment': m.get('alignment'),
        'ac': ac[0].get('value'), 'hp': m.get('hit_points'), 'hitDice': m.get('hit_points_roll') or m.get('hit_dice'),
        'speed': ', '.join(f"{k} {v}" if k != 'walk' else v for k, v in (m.get('speed') or {}).items() if isinstance(v, str)),
        'scores': [m.get(k) for k in ['strength', 'dexterity', 'constitution', 'intelligence', 'wisdom', 'charisma']],
        'saves': saves, 'skills': skills,
        'vulnerable': m.get('damage_vulnerabilities') or [], 'resist': m.get('damage_resistances') or [], 'immune': m.get('damage_immunities') or [],
        'conditionImmune': [c['name'] if isinstance(c, dict) else c for c in (m.get('condition_immunities') or [])],
        'senses': ', '.join(f"{k.replace('_', ' ')} {v}" for k, v in (m.get('senses') or {}).items()),
        'languages': m.get('languages') or '—', 'cr': m.get('challenge_rating'), 'xp': m.get('xp'), 'pb': m.get('proficiency_bonus'),
        'traits': actions(m.get('special_abilities')), 'actions': actions(m.get('actions')), 'bonusActions': actions(m.get('bonus_actions')),
        'reactions': actions(m.get('reactions')), 'legendary': actions(m.get('legendary_actions')),
    })
write('monsters', 'MONSTERS', monsters)

# ---------------------------------------------------------------- full rules text for hand-modelled content
text = {}
for f in load('Features'):
    if f.get('class'):
        text[f"class:{f['class']['index']}:{f['name']}"] = clean(f.get('description') or '\n'.join(f.get('desc', [])))
for s in load('Subclasses'):
    text[f"subclass:{s['name']}"] = clean(s.get('description') or '')
    for f in s.get('features', []):
        text[f"sub:{s['name']}:{f['name']}"] = clean(f.get('description') or '')
for f in load('Feats'):
    text[f"feat:{f['index']}"] = clean(f.get('description') or '')
for t in load('Traits'):
    for sp in t.get('species', []) or [{'index': '*'}]:
        text[f"trait:{sp['index']}:{t['name']}"] = clean(t.get('description') or '')
for b in load('Backgrounds'):
    if b.get('description'):
        text[f"background:{b['index']}"] = clean(b['description'])
for c in load('Conditions'):
    text[f"condition:{c['index']}"] = clean(c.get('description') or '\n'.join(c.get('desc', [])))
write('rules-text', 'RULES_TEXT', text)
